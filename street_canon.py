"""Канонические имена улиц: слияние дублей и разведение одноимённых.

Правила нужны, потому что в выгрузке Росреестра тип улицы часто отброшен,
а одинаковые названия встречаются в разных районах / кадастровых кварталах.
"""

from __future__ import annotations

import re

# Кадастровые районы СПб: 78:31 Центральный, 78:37 Колпинский, 78:42 Пушкинский (Шушары).
_TVERSKAYA_KOLPINO_PREFIXES = ("78:37:",)
_PUSHKINSKAYA_SHUSHARY_PREFIXES = ("78:42:",)
_PUSHKINSKAYA_KOLPINO_PREFIXES = ("78:37:",)
# Кварталы площади Аврова vs улицы Аврова (Петергоф, 78:40).
_AVROVA_SQUARE_QUARTERS = (
    "78:40:0019249",
    "78:40:0019251",
)
_AVROVA_STREET_QUARTERS = (
    "78:40:0019284",
    "78:40:0019259",
)

_TYPE_SUFFIX = re.compile(
    r"\s+(?:проспект|улица|площадь|переулок|набережная|бульвар|шоссе|"
    r"аллея|проезд|дорога)$",
    re.IGNORECASE,
)
_PAREN = re.compile(r"\s*\([^)]*\)\s*")

# Слияние вариантов написания / уточнений в скобках → канон каталога.
_MERGE_BY_CORE: dict[str, str] = {
    "непокоренных": "Непокоренных",
    "английский": "Английский",
    "переведенская": "Переведенская",
    "пискаревский": "Пискаревский",
    "полоцкая": "Полоцкая",
    "политрука пасечника": "Политрука Пасечника",
    "приозерское": "Приозерское",
    "пугачева": "Пугачева",
    "анциферовская": "Анциферовская",
    "большая озерная": "Большая Озерная",
    "бородачева": "Бородачева",
    "взлетная": "Взлетная",
    "героев": "Героев",
    "грибалевой": "Грибалевой",
    "долгоозерная": "Долгоозерная",
    "изборская": "Изборская",
    "ковалевская": "Ковалевская",
    "кокколевская": "Кокколевская",
    "комендантский": "Комендантский",
    "королева": "Королева",
    # Колпинское шоссе: ярлыки Славянка/Детскосельский пересекаются по кварталам.
    "колпинское": "Колпинское",
    "образцовая": "Образцовая",
    "ольгинская": "Ольгинская",
    "обводного канала": "Обводного канала",
    "набережная": "Набережная",
    "ростовская": "Ростовская",
    "саперная": "Саперная",
    "северный": "Северный",
    "славянская": "Славянская",
    "учхозная": "Учхозная",
    "хабаровская": "Хабаровская",
    "юкковское": "Юкковское",
}


def _norm_key(name: str) -> str:
    return " ".join((name or "").strip().lower().replace("ё", "е").split())


def _base_without_type(name: str) -> str:
    text = " ".join((name or "").strip().split())
    return _TYPE_SUFFIX.sub("", text).strip() or text


def _core_name(name: str) -> str:
    """Имя без типа улицы и без уточнения в скобках."""
    text = _PAREN.sub(" ", name or "")
    return _norm_key(_base_without_type(text))


def canonicalize_street(street: str, quarter_cad_number: str = "") -> str:
    """Возвращает каноническое имя улицы для каталога и поиска."""
    name = " ".join((street or "").strip().split())
    if not name:
        return name

    key = _norm_key(name)
    base = _norm_key(_base_without_type(name))
    core = _core_name(name)
    quarter = (quarter_cad_number or "").strip()

    # Тверская: Центр (78:31) vs Колпино (78:37).
    if core == "тверская":
        if any(quarter.startswith(p) for p in _TVERSKAYA_KOLPINO_PREFIXES):
            return "Тверская (Колпино)"
        if "колпино" in key:
            return "Тверская (Колпино)"
        return "Тверская"

    # Пушкинская: Центр (78:31) vs Шушары/Пушкинский (78:42) vs Колпино (78:37).
    if core == "пушкинская":
        if "шушар" in key or any(
            quarter.startswith(p) for p in _PUSHKINSKAYA_SHUSHARY_PREFIXES
        ):
            return "Пушкинская (Шушары)"
        if "колпино" in key or any(
            quarter.startswith(p) for p in _PUSHKINSKAYA_KOLPINO_PREFIXES
        ):
            return "Пушкинская (Колпино)"
        return "Пушкинская"

    # Заводская: несколько одноимённых улиц в разных районах.
    # 78:12 Усть-Славянка, 78:36 Парголово, 78:37 Понтонный, 78:38 Песочный.
    if core == "заводская":
        if "усть" in key or "слав" in key or quarter.startswith("78:12:"):
            return "Заводская (Усть-Славянка)"
        if "песочн" in key or quarter.startswith("78:38:"):
            return "Заводская (Песочный)"
        if "парголов" in key or quarter.startswith("78:36:"):
            return "Заводская (Парголово)"
        if "понтон" in key or quarter.startswith("78:37:"):
            return "Заводская (Понтонный)"
        return "Заводская"

    # Аврова: площадь и улица в Петергофе — разные топонимы.
    if core == "аврова":
        if "площад" in key:
            return "Аврова площадь"
        if "улиц" in key:
            return "Аврова"
        if any(quarter.startswith(q) for q in _AVROVA_SQUARE_QUARTERS):
            return "Аврова площадь"
        if any(quarter.startswith(q) for q in _AVROVA_STREET_QUARTERS):
            return "Аврова"
        return "Аврова"

    # Коммунаров: Горелово (78:40) ≠ Ломоносовский (47:14).
    if core == "коммунаров":
        if "горелов" in key or quarter.startswith("78:40:"):
            return "Коммунаров (Горелово)"
        return "Коммунаров"

    # Кооперативная: Торфяное (78:36:13…) ≠ Парголово (78:36:00…) ≠ Петергоф (78:40).
    if core == "кооперативная":
        if "торфян" in key or quarter.startswith("78:36:13"):
            return "Кооперативная (Торфяное)"
        if quarter.startswith("78:40:"):
            return "Кооперативная (Петергоф)"
        return "Кооперативная"

    # Красносельское шоссе: разные ветки по районам.
    if core == "красносельское":
        if "горелов" in key or quarter.startswith("78:40:"):
            return "Красносельское (Горелово)"
        if "пушкин" in key or quarter.startswith("78:42:"):
            return "Красносельское (Пушкин)"
        # 47:14 и прочие → основное шоссе (в т.ч. «Красносельское шоссе»).
        return "Красносельское"

    # Новая: Пушкин ≠ пос. Динамо (разные кварталы 78:42).
    if core == "новая":
        if "динамо" in key or quarter.startswith("78:42:00164"):
            return "Новая (Динамо)"
        return "Новая"

    # Новое (одна сделка, 78:38 у Песочного/Курортного) → Новое шоссе.
    if core == "новое":
        return "Новое шоссе"

    # Прядильный → переулок (Коломна).
    if core == "прядильный":
        return "Прядильный переулок"

    # Почтовый: Стрельна (78:40) vs Ушково (78:38).
    if core == "почтовый":
        if "ушков" in key or quarter.startswith("78:38:"):
            return "Почтовый (Ушково)"
        return "Почтовый (Стрельна)"

    # Римского-Корсакова (+ опечатка «Корсакого»).
    if "римского-корсак" in key or core.startswith("римского-корсак"):
        return "Римского-Корсакова"

    # Саперный переулок (Центр) ≠ Саперная улица (Пушкин).
    if core == "саперный":
        return "Саперный переулок"

    # Советский проспект: Усть-Славянка (78:12); редкие выбросы — отдельно.
    if core == "советский":
        if (
            "усть" in key
            or "слав" in key
            or quarter.startswith("78:12:")
            or not quarter
        ):
            return "Советский"
        if quarter.startswith("78:37:"):
            return "Советский (Колпино)"
        if quarter.startswith("78:38:"):
            return "Советский (Песочный)"
        return "Советский"

    # Сосновая: Курортный (78:38) ≠ Ржевка (78:11).
    if core == "сосновая":
        if "ржевк" in key or quarter.startswith("78:11:"):
            return "Сосновая (Ржевка)"
        return "Сосновая"

    # Средний проспект В.О. (78:06) ≠ «Средний» в Курортном (78:38).
    if core in {"средний", "средний в.о.", "средний в о"} or key.startswith(
        "средний в.о"
    ):
        if "в.о" in key or "в о" in key or quarter.startswith("78:06:"):
            return "Средний В.О."
        return "Средний"

    # Старожиловская: Парголово (78:36:00) ≠ Торфяное (78:36:13).
    if core == "старожиловская":
        if "торфян" in key or quarter.startswith("78:36:13"):
            return "Старожиловская (Торфяное)"
        return "Старожиловская"

    # Центральная: Песочный / Металлострой / Детскосельский (Шушары) — разные районы.
    if core == "центральная":
        if (
            "детскосельск" in key
            or "шушар" in key
            or quarter.startswith("78:42:")
        ):
            return "Центральная (Детскосельский)"
        if "песочн" in key or "белоостров" in key or quarter.startswith("78:38:"):
            return "Центральная (Песочный)"
        if (
            "металлострой" in key
            or "колпин" in key
            or quarter.startswith("78:37:")
        ):
            return "Центральная (Металлострой)"
        return "Центральная"

    # «Набережная реки …» / «… набережная» с уточнением — не трогаем через merge.
    if core == "набережная" and (
        "реки" in key or "канала" in key or "каналу" in key
    ):
        return name

    # Простые слияния дублей (ё/е, скобки, с типом / без типа).
    merged = _MERGE_BY_CORE.get(core)
    if merged:
        return merged

    # Совместимость со старыми ключами до _core_name.
    if base == "непокоренных" or key in {
        "непокоренных",
        "непокоренных проспект",
        "непокорённых",
        "непокорённых проспект",
    }:
        return "Непокоренных"
    if base == "английский" or key in {"английский", "английский проспект"}:
        return "Английский"

    return name
